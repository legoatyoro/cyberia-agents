# 3. learn_from_response
# ---------------------------------------------------------------------------

def learn_from_response(
    url: str,
    payload: str,
    status_code: int,
    response_headers: dict,
    waf_name: str,
    payload_type: str = "",
    verdict: str = "",
) -> dict:
    """
    Enregistre le feedback dans waf_feedback.db.
    Si verdict=CONFIRMED : booste le score du payload dans payload_lab.db.
    Retourne {"blocked": bool, "bypass_rate": float, "total": int, "bypassed": int}.
    """
    blocked = 0 if verdict == "CONFIRMED" else (1 if status_code in (403, 406, 429, 503) else 0)

    con = _init_feedback_db()
    con.execute(
        "INSERT INTO feedback (url, payload, waf, blocked, payload_type, timestamp) VALUES (?,?,?,?,?,?)",
        (url, payload, waf_name, blocked, payload_type, _now()),
    )
    con.commit()

    row = con.execute(
        "SELECT COUNT(*), SUM(CASE WHEN blocked=0 THEN 1 ELSE 0 END) FROM feedback WHERE waf=?",
        (waf_name,),
    ).fetchone()
    total = row[0] or 0
    bypassed = int(row[1] or 0)
    bypass_rate = round(bypassed / total * 100, 1) if total > 0 else 0.0
    con.close()

    # Booster le score dans payload_lab.db si bypass confirme
    if blocked == 0 and verdict == "CONFIRMED" and PAYLOAD_LAB_DB.exists():
        try:
            pcon = sqlite3.connect(str(PAYLOAD_LAB_DB), timeout=5)
            pcon.execute(
                "UPDATE results SET score = MIN(score + 10, 100), bypass_confirmed = 1 "
                "WHERE payload = ? AND payload_type LIKE ?",
                (payload, f"%{payload_type}%"),
            )
            pcon.execute(
                "UPDATE imported_payloads SET waf_score = MIN(waf_score + 1, 15) WHERE payload = ?",
                (payload,),
            )
            pcon.commit()
            pcon.close()
        except Exception:
            pass

    return {"blocked": bool(blocked), "bypass_rate": bypass_rate, "total": total, "bypassed": bypassed}


# ---------------------------------------------------------------------------
# 4. get_bypass_stats
# ---------------------------------------------------------------------------

def get_bypass_stats(waf_name: str) -> dict:
    """
    Retourne les statistiques de bypass pour un WAF donne.
    """
    empty = {"waf": waf_name, "total": 0, "bypassed": 0, "bypass_rate": 0.0, "best_payloads": [], "by_type": {}}
    if not WAF_FEEDBACK_DB.exists():
        return empty

    try:
        con = sqlite3.connect(str(WAF_FEEDBACK_DB), timeout=5)

        row = con.execute(
            "SELECT COUNT(*), SUM(CASE WHEN blocked=0 THEN 1 ELSE 0 END) FROM feedback WHERE waf=?",
            (waf_name,),
        ).fetchone()
        total = row[0] or 0
        bypassed = int(row[1] or 0)
        bypass_rate = round(bypassed / total * 100, 1) if total > 0 else 0.0

        best_rows = con.execute(
            "SELECT payload, payload_type FROM feedback WHERE waf=? AND blocked=0 ORDER BY id DESC LIMIT 10",
            (waf_name,),
        ).fetchall()

        type_rows = con.execute(
            "SELECT payload_type, COUNT(*), SUM(CASE WHEN blocked=0 THEN 1 ELSE 0 END) "
            "FROM feedback WHERE waf=? GROUP BY payload_type",
            (waf_name,),
        ).fetchall()
        con.close()
    except Exception:
        return empty

    by_type: dict = {}
    for r in type_rows:
        ptype = r[0] or "unknown"
        t = r[1] or 0
        b = int(r[2] or 0)
        by_type[ptype] = {"total": t, "bypassed": b, "rate": round(b / t * 100, 1) if t > 0 else 0.0}

    return {
        "waf": waf_name,
        "total": total,
        "bypassed": bypassed,
        "bypass_rate": bypass_rate,
        "best_payloads": [{"payload": r[0], "type": r[1]} for r in best_rows],
        "by_type": by_type,
    }


