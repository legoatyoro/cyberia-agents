def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _init_feedback_db() -> sqlite3.Connection:
    CYBERIA_DIR.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(str(WAF_FEEDBACK_DB), timeout=10)
    con.execute("""
        CREATE TABLE IF NOT EXISTS feedback (
            id           INTEGER PRIMARY KEY AUTOINCREMENT,
            url          TEXT,
            payload      TEXT,
            waf          TEXT,
            blocked      INTEGER DEFAULT 1,
            payload_type TEXT,
            timestamp    TEXT
        )
    """)
    con.execute("CREATE INDEX IF NOT EXISTS idx_fb_waf ON feedback (waf)")
    con.commit()
    return con


def _write_supervisor_prompt(entry: dict) -> None:
    if not SUPERVISOR_PROMPTS.exists():
        data: dict = {"generated_at": _now(), "priority_prompts": []}
    else:
        try:
            data = json.loads(SUPERVISOR_PROMPTS.read_text(encoding="utf-8"))
        except Exception:
            data = {"generated_at": _now(), "priority_prompts": []}

    prompts: list = data.get("priority_prompts", [])
    # Remplacer entree existante meme categorie + meme WAF
    prompts = [
        p for p in prompts
        if not (p.get("category") == entry["category"] and p.get("waf_target") == entry.get("waf_target"))
    ]
    prompts.insert(0, entry)
    data["priority_prompts"] = prompts[:20]
    data["generated_at"] = _now()
    SUPERVISOR_PROMPTS.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")


def _inject_memory(category: str, content: str) -> None:
    if not MEMORY_HUB_DB.exists():
        return
    try:
        con = sqlite3.connect(str(MEMORY_HUB_DB), timeout=5)
        con.execute(
            "INSERT INTO memories (source, category, content, created_at) VALUES (?,?,?,?)",
            ("waf_fingerprint", category, content, _now()),
        )
        con.commit()
        con.close()
    except Exception:
        pass


