# 1. fingerprint_waf
# ---------------------------------------------------------------------------

def fingerprint_waf(url: str, timeout: int = 8) -> dict:
    """
    Detecte le WAF sur url par analyse des headers et du body des reponses.
    Retourne {"waf": str, "confidence": int, "headers": dict, "signatures": list}.
    """
    result: dict = {"waf": "unknown", "confidence": 0, "headers": {}, "signatures": []}

    session = requests.Session()
    session.headers["User-Agent"] = "CYBERIA-WafDetector/1.0"

    all_headers: dict[str, str] = {}
    bodies: list[str] = []

    # Requete neutre
    try:
        r0 = session.get(url, timeout=timeout, allow_redirects=True)
        all_headers.update({k.lower(): v for k, v in r0.headers.items()})
        bodies.append(r0.text[:4000])
    except Exception:
        pass

    # Requetes de probe (s'arrete au premier blocage)
    for probe in _PROBE_PAYLOADS:
        try:
            probe_url = url.rstrip("/") + "/?q=" + probe
            r = session.get(probe_url, timeout=timeout, allow_redirects=True)
            all_headers.update({k.lower(): v for k, v in r.headers.items()})
            bodies.append(r.text[:4000])
            if r.status_code in (403, 406, 429, 503):
                break
        except Exception:
            continue

    if not bodies:
        return result

    result["headers"] = dict(all_headers)
    combined_body = " ".join(bodies).lower()

    best_name = "unknown"
    best_score = 0
    best_sig: dict = {}

    for sig in WAF_SIGNATURES:
        score = 0
        matched: list[str] = []

        for hk in sig["header_keys"]:
            if hk.lower() in all_headers:
                score += 35
                matched.append(f"header:{hk}")

        for hk, hv in sig["header_values"].items():
            if hv.lower() in all_headers.get(hk.lower(), "").lower():
                score += 30
                matched.append(f"header:{hk}={hv}")

        for bs in sig["body_strings"]:
            if bs.lower() in combined_body:
                score += 25
                matched.append(f"body:{bs}")

        if score > best_score:
            best_score = score
            best_name = sig["name"]
            best_sig = sig
            result["signatures"] = matched

    if best_score > 0:
        base = best_sig.get("confidence_base", 50)
        # chaque tranche de 5 pts au-dessus de 25 ajoute 1 pt de confiance
        bonus = min(20, (best_score - 25) // 5)
        result["confidence"] = min(99, base + bonus)
        result["waf"] = best_name

    return result


