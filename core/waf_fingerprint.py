def _cli() -> None:
    parser = argparse.ArgumentParser(
        description="CYBERIA WAF Fingerprinter",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Exemples:\n"
            "  python core/waf_fingerprint.py --url http://monsite.com\n"
            "  python core/waf_fingerprint.py --url http://monsite.com --category xss --generate-payloads\n"
            "  python core/waf_fingerprint.py --stats cloudflare\n"
        ),
    )
    parser.add_argument("--url", help="URL cible a analyser")
    parser.add_argument("--category", default="xss", help="Categorie de vuln (xss, sqli, lfi, rce, ssti, ssrf)")
    parser.add_argument("--generate-payloads", action="store_true", dest="generate",
                        help="Generer des prompts de bypass dans supervisor_prompts.json")
    parser.add_argument("--stats", metavar="WAF_NAME",
                        help="Afficher les statistiques de bypass pour un WAF")
    args = parser.parse_args()

    if args.stats:
        stats = get_bypass_stats(args.stats)
        print(f"\n=== STATS BYPASS : {stats['waf'].upper()} ===")
        print(f"  Total tests    : {stats['total']}")
        print(f"  Bypasses       : {stats['bypassed']}")
        print(f"  Taux de bypass : {stats['bypass_rate']}%")
        if stats["by_type"]:
            print("\n  Par type :")
            for ptype, d in sorted(stats["by_type"].items()):
                print(f"    {ptype:10s} : {d['bypassed']}/{d['total']} ({d['rate']}%)")
        if stats["best_payloads"]:
            print("\n  Meilleurs payloads :")
            for bp in stats["best_payloads"][:5]:
                print(f"    [{bp['type'] or '?':6s}] {bp['payload'][:70]}")
        return

    if not args.url:
        parser.print_help()
        return

    print(f"\n[*] Fingerprinting WAF sur : {args.url}")
    result = fingerprint_waf(args.url)

    print(f"\n=== RESULTAT ===")
    print(f"  WAF detecte  : {result['waf'].upper()}")
    print(f"  Confiance    : {result['confidence']}%")
    if result["signatures"]:
        print(f"  Signatures   :")
        for s in result["signatures"]:
            print(f"    - {s}")
    interesting_hdrs = {k: v for k, v in result["headers"].items()
                        if any(kw in k for kw in ["cf-", "sucuri", "server", "x-powered", "x-iinfo",
                                                   "akamai", "fortiwa", "barra_", "x-amz"])}
    if interesting_hdrs:
        print(f"  Headers WAF  :")
        for k, v in interesting_hdrs.items():
            print(f"    {k}: {v[:80]}")

    if args.generate:
        cat = args.category
        print(f"\n[*] Generation du prompt [{cat.upper()}] pour {result['waf'].upper()}...")
        entry = generate_bypass_prompts(result["waf"], cat)
        print(f"[+] Ecrit dans supervisor_prompts.json (priorite={entry['priority']}, ttl={entry['ttl']})")
        print(f"[+] Injecte dans memory_hub.db")
        print(f"\n    Prompt : {entry['prompt'][:120]}...")


if __name__ == "__main__":
    _cli()
