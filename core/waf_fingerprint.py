# 2. generate_bypass_prompts
# ---------------------------------------------------------------------------

def generate_bypass_prompts(waf_name: str, category: str) -> dict:
    """
    Construit un prompt MiMo specifique au WAF detecte, l'ecrit dans
    supervisor_prompts.json (ttl=10, priorite=critical) et l'injecte dans
    memory_hub.db.
    Retourne le dict de l'entree creee.
    """
    strategies = WAF_BYPASS_STRATEGIES.get(waf_name, WAF_BYPASS_STRATEGIES["unknown"])
    technique_str = strategies.get(category, strategies.get("xss", ""))
    waf_display = waf_name.upper()

    prompt = (
        f"Generate 8 {category.upper()} payloads specifically designed to bypass {waf_display} WAF rules. "
        f"Focus on: {technique_str}. "
        f"Each payload must evade {waf_display} detection signatures. "
        f"Output JSON only: "
        f"{{\"mutations\":[{{\"payload\":\"...\",\"type\":\"{category}\",\"technique\":\"...\"}}]}}"
    )

    entry = {
        "category": category,
        "prompt": prompt,
        "reason": f"WAF {waf_display} detecte — payloads de bypass specifiques requis.",
        "ttl": 10,
        "priority": "critical",
        "waf_target": waf_name,
        "generated_at": _now(),
    }

    _write_supervisor_prompt(entry)
    _inject_memory(
        category="waf_detection",
        content=f"WAF detecte: {waf_name} | Categorie: {category} | Prompt bypass genere.",
    )
    return entry


